import { expect, test } from "@playwright/test"

// Сквозной сценарий #26: после старта на чистой базе демо-стенд сразу
// работоспособен — на главной уже есть два дефолтных Типа звонка,
// посеянных сервером (seed-if-empty). Спеки делят один сервер и базу,
// поэтому проверяется видимость дефолтов, а не состав списка целиком.

test("на свежем сервере главная показывает дефолтные Типы звонка", async ({ page }) => {
  await page.goto("/")

  await expect(page.getByRole("link", { name: "Интро-звонок — 15 минут" })).toBeVisible()
  await expect(page.getByRole("link", { name: "Консультация — 30 минут" })).toBeVisible()
})
